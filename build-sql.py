#!/usr/bin/env python3
"""Packs every supabase/*.sql file into backend/src/sqltext.js so the admin SQL panel can show and copy them.
Run it again whenever you add or change a .sql file:  python3 build-sql.py"""
import glob, json, os
files = sorted(glob.glob('supabase/*.sql'), key=lambda p: (os.path.basename(p) != 'schema.sql', os.path.basename(p)))
out = {os.path.basename(p): open(p, encoding='utf-8').read() for p in files}
with open('backend/src/sqltext.js', 'w', encoding='utf-8') as f:
    f.write('// GENERATED by build-sql.py from supabase/*.sql. Do not edit by hand.\nexport default ' + json.dumps(out, indent=1, ensure_ascii=False) + ';\n')
print('sqltext.js built from', len(out), 'SQL files:', ', '.join(out))
